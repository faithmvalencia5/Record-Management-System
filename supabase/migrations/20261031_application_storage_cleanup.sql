-- Queue applicant Storage objects before an application row is deleted.
-- Storage files are not covered by PostgreSQL foreign-key cascades.
-- A Supabase Database Webhook invokes the Edge Function after this row is inserted.

CREATE TABLE IF NOT EXISTS public.application_storage_cleanup_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id text NOT NULL,
  bucket_id text NOT NULL DEFAULT 'documents',
  object_paths text[] NOT NULL DEFAULT ARRAY[]::text[],
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
  attempt_count integer NOT NULL DEFAULT 0,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_application_storage_cleanup_pending
  ON public.application_storage_cleanup_queue (status, created_at);

ALTER TABLE public.application_storage_cleanup_queue ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.application_storage_cleanup_queue FROM anon, authenticated;
GRANT ALL ON TABLE public.application_storage_cleanup_queue TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.application_storage_cleanup_queue_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.enqueue_application_storage_cleanup()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, storage
AS $$
DECLARE
  paths text[];
BEGIN
  SELECT COALESCE(array_agg(o.name ORDER BY o.name), ARRAY[]::text[])
    INTO paths
  FROM storage.objects AS o
  WHERE o.bucket_id = 'documents'
    AND left(o.name, length(OLD.application_id::text) + 1) = OLD.application_id::text || '/';

  IF cardinality(paths) > 0 THEN
    INSERT INTO public.application_storage_cleanup_queue (
      application_id,
      bucket_id,
      object_paths
    )
    VALUES (
      OLD.application_id::text,
      'documents',
      paths
    );
  END IF;

  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_enqueue_application_storage_cleanup
  ON public.applications;

CREATE TRIGGER trg_enqueue_application_storage_cleanup
BEFORE DELETE ON public.applications
FOR EACH ROW
EXECUTE FUNCTION public.enqueue_application_storage_cleanup();
